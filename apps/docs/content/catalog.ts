export interface DemoEntry {
  /** Sleutel van het demobestand in /demos. */
  key: string;
  title: string;
  description?: string;
  /** Inhoud links uitlijnen in plaats van centreren. */
  align?: "center" | "start" | "block";
  /** Toont een "nieuw"-label bij deze demo. */
  isNew?: boolean;
  /** Toont een "bijgewerkt"-label bij deze demo. Wordt genegeerd als isNew aanstaat. */
  isUpdated?: boolean;
}

export interface ComponentEntry {
  slug: string;
  name: string;
  description: string;
  category: string;
  /** Bestanden uit packages/ui die dit component nodig heeft. */
  files: string[];
  /** Andere componenten die mee gekopieerd worden. */
  dependsOn?: string[];
  /** npm-packages die dit component nodig heeft. Alleen de motion-laag gebruikt dit. */
  requires?: string[];
  demos: DemoEntry[];
  /** Namen van interfaces waarvan de props-tabel getoond wordt. */
  props?: string[];
  notes?: string[];
  /** Toont een "nieuw"-label in de navigatie en op de pagina. */
  isNew?: boolean;
  /** Toont een "bijgewerkt"-label in de navigatie en op de pagina. Wordt genegeerd als isNew aanstaat. */
  isUpdated?: boolean;
}

